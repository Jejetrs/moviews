-- Moviews — database schema for Neon (PostgreSQL 15+)
--
-- Run once against your Neon database:
--   npm run db:migrate            (uses DATABASE_URL from .env)
--   psql "$DATABASE_URL" -f database/schema.sql
--
-- The script is idempotent: it is safe to run again after pulling updates.
--
-- Titles come from TMDB, so they are referenced by (media_type, tmdb_id)
-- instead of a local "movies" table. This matches the app's item key, e.g. "movie-603".

BEGIN;

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR(255) NOT NULL,
  password    VARCHAR(255) NOT NULL,            -- bcrypt hash, never the plain password
  username    VARCHAR(100) NOT NULL,
  fullname    VARCHAR(255) NOT NULL,
  avatar      TEXT,                             -- small data URL produced by the profile page
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT users_avatar_size CHECK (avatar IS NULL OR length(avatar) <= 300000)
);

-- Email and username are unique regardless of letter case.
CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users (lower(email));
CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique ON users (lower(username));

DROP TRIGGER IF EXISTS users_set_updated_at ON users;
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- watchlist_items — titles a user saved (a snapshot of what the cards show)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS watchlist_items (
  user_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  media_type    TEXT NOT NULL CHECK (media_type IN ('movie', 'tv')),
  tmdb_id       BIGINT NOT NULL CHECK (tmdb_id > 0),
  title         VARCHAR(500) NOT NULL,
  poster_path   VARCHAR(255),
  vote_average  NUMERIC(3, 1) NOT NULL DEFAULT 0 CHECK (vote_average BETWEEN 0 AND 10),
  release_date  DATE,
  overview      TEXT NOT NULL DEFAULT '',
  added_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, media_type, tmdb_id)
);

CREATE INDEX IF NOT EXISTS watchlist_items_user_added_idx
  ON watchlist_items (user_id, added_at DESC);

-- ---------------------------------------------------------------------------
-- ratings — one 1–5 star rating per user and title
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ratings (
  user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  media_type  TEXT NOT NULL CHECK (media_type IN ('movie', 'tv')),
  tmdb_id     BIGINT NOT NULL CHECK (tmdb_id > 0),
  value       SMALLINT NOT NULL CHECK (value BETWEEN 1 AND 5),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, media_type, tmdb_id)
);

DROP TRIGGER IF EXISTS ratings_set_updated_at ON ratings;
CREATE TRIGGER ratings_set_updated_at BEFORE UPDATE ON ratings
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- reviews — community reviews shown on a title's detail page
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reviews (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  media_type  TEXT NOT NULL CHECK (media_type IN ('movie', 'tv')),
  tmdb_id     BIGINT NOT NULL CHECK (tmdb_id > 0),
  rating      SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  body        VARCHAR(600) NOT NULL CHECK (length(btrim(body)) > 0),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS reviews_title_created_idx
  ON reviews (media_type, tmdb_id, created_at DESC);
CREATE INDEX IF NOT EXISTS reviews_user_idx ON reviews (user_id);

COMMIT;
